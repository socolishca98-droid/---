// tests/assistant-base-from-org.test.mjs
//
// Помощник сборки отталкивается от адреса ОРГАНИЗАЦИИ, а не от произвольного
// города. Подсказки предлагают ближайшие к базе места.
//
// Почему: у каждой компании свой адрес, и маршрут обязан начинаться от её
// стоянки. Прежняя версия сортировала города погрузки по числу грузов —
// вверху оказывался случайный город с биржи, а не тот, куда логисту ехать.
// Пользователь увидел на экране «Денисово д. · 12» и справедливо спросил
// «что это за локации?» — подсказка не имела отношения к его базе.
//
// Этот тест стережет правило на уровне исходников.

import test from "node:test"
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import { join } from "node:path"

const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "")
const PAGE = readFileSync(join(ROOT, "app/lm/routes/assistant/page.tsx"), "utf8")

test("база берётся из настроек организации (baseAddress)", () => {
  assert.match(PAGE, /settings\?\.baseAddress/, "база должна приходить из /api/fleet/settings")
  assert.match(PAGE, /setBaseCity\(address\)/, "адрес организации запоминается как база")
})

test("координаты базы тоже читаются из настроек", () => {
  assert.match(PAGE, /settings\?\.baseLat/, "координаты стоянки берутся из настроек")
  assert.match(PAGE, /settings\?\.baseLng/)
})

test("подсказки городов сортируются по близости к базе, а не по числу грузов", () => {
  // В сортировке первым критерием идёт километраж от базы
  assert.match(
    PAGE,
    /if \(a\.km !== null && b\.km !== null\) return a\.km - b\.km/,
    "города должны сортироваться по расстоянию от базы",
  )
  // Число грузов — только когда расстояние неизвестно
  assert.match(PAGE, /return b\.count - a\.count/, "по числу грузов — лишь как запасной вариант")
})

test("на экране показаны сами грузы, а не только названия городов", () => {
  // Иначе пользователь видит список городов и спрашивает «где заказы?»
  assert.match(PAGE, /Грузы на бирже — ближе к вашей базе/, "должен быть список грузов")
  assert.match(PAGE, /nearestLoads/, "грузы сортируются от базы")
})

test("база организации показана пользователю явно", () => {
  assert.match(PAGE, /Ваша база из настроек/, "пользователь должен видеть, откуда база")
})

test("город без координат не роняет сортировку", () => {
  // km остаётся null — город уйдёт в конец списка, но не сломает расчёт
  assert.match(PAGE, /: null\s*\n\s*\}/, "неизвестное расстояние = null")
})
