// tests/geo-federal-city.test.mjs
//
// Города федерального значения в резолве (находка Н1, 8.11):
// регион города в справочнике — сам город («Москва (регион)» → ключ
// «москва»), а адрес пишут с областью («Москва, Московская область» →
// «московская»). До фикса фильтр по региону был пуст, и город не находился
// НИ В КАКОМ написании: подсказка «укажите область» не помогала.
//
// Что фиксирует тест:
//   · «Москва, Московская область» — resolves в город Москву;
//   · «Москва, Кировская область» — в деревню (прямой регион, не алиас);
//   · голая «Москва» — остаётся честной неоднозначностью (4 места,
//     4 региона): резолв требует указания региона, догадок не делает;
//   · «Санкт-Петербург, Ленинградская область» — работает (и через
//     уникальность имени, и через алиас);
//   · обычные города не затронуты: «Ярославль, Ярославская область»
//     резолвится, «Ярославль» без области — неоднозначен (3 ярославля).

import test from "node:test"
import assert from "node:assert/strict"

import {
  buildPlaceIndex,
  resolvePlace,
} from "../.test-build/lib/routing/geo/resolve.js"
import { parseAddress } from "../.test-build/lib/routing/geo/address.js"

// Срез настоящего справочника: Москва-город + три деревни-омонима,
// СПб, Севастополь и три ярославля (город и соседи-тёзки).
const ROWS = [
  { name: "Москва", region: "Москва (регион)", lat: 55.75, lon: 37.62 },
  { name: "Москва д., Кировская область", region: "Кировская область", lat: 57.97, lon: 49.11 },
  { name: "Москва д., Тверская область", region: "Тверская область", lat: 56.92, lon: 32.16 },
  { name: "Москва д., Псковская область", region: "Псковская область", lat: 57.45, lon: 29.19 },
  { name: "Санкт-Петербург", region: "Санкт-Петербург (регион)", lat: 59.94, lon: 30.31 },
  { name: "Санкт-Петербург (Колпинский)", region: "Санкт-Петербург (регион)", lat: 59.75, lon: 30.59 },
  { name: "Севастополь", region: "Севастополь (регион)", lat: 44.62, lon: 33.53 },
  { name: "Ярославль", region: "Ярославская область", lat: 57.63, lon: 39.87 },
  { name: "Ярославль д., Кировская область", region: "Кировская область", lat: 57.9, lon: 49.2 },
  { name: "Ярославль п., Новосибирская область", region: "Новосибирская область", lat: 54.9, lon: 76.5 },
]

const index = buildPlaceIndex(ROWS)

function resolve(raw) {
  return resolvePlace(raw, parseAddress(raw), index)
}

test("«Москва, Московская область» — город (алиас федерального города)", () => {
  const found = resolve("Москва, Московская область")
  assert.equal(found.point?.name, "Москва")
  assert.equal(found.status !== "ambiguous", true)
})

test("«Москва, Московская обл.» — город (сокращённая форма региона)", () => {
  const found = resolve("Москва, Московская обл.")
  assert.equal(found.point?.name, "Москва")
})

test("«Москва, Кировская область» — деревня, не город", () => {
  const found = resolve("Москва, Кировская область")
  assert.equal(found.point?.name, "Москва д., Кировская область")
})

test("голая «Москва» — честная неоднозначность, а не догадка", () => {
  const found = resolve("Москва")
  assert.equal(found.point, null)
  assert.equal(found.status, "ambiguous")
  assert.match(found.note ?? "", /неоднозначно|4 местах|регион не указан/)
})

test("«Санкт-Петербург, Ленинградская область» — город", () => {
  const found = resolve("Санкт-Петербург, Ленинградская область")
  assert.equal(found.point?.name, "Санкт-Петербург")
})

test("обычные города не затронуты: Ярославль с областью — да, без — нет", () => {
  assert.equal(resolve("Ярославль, Ярославская область").point?.name, "Ярославль")
  assert.equal(resolve("Ярославль").status, "ambiguous")
})
