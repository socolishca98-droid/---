// lib/logist-mobile/city-norm.ts
//
// Нормализация названий городов для стыковки цепочки маршрута.
//
// Зачем: в биржевых грузах один и тот же город пишется по-разному —
// «Ворсино с. (Боровский р-н)» в одном грузе, «Ворсино» в другом,
// «Ступино г. (г.о. Ступино)» против «Ступино г.». Без нормализации
// помощник считает их разными городами и не связывает грузы в цепочку.
//
// Правила:
//   * выбрасываем уточнения в скобках: «(Боровский р-н)», «(г.о. Ступино)»;
//   * выбрасываем тип населённого пункта: с., д., г., пос., х., ст-ца, сл., п., м.;
//   * всё в нижний регистр, ё → е, кавычки и точки убираем.
//
// Важно: НЕ режем хвост после пробела — «Кировская ст-ца» должна остаться
// «кировская», а не превратиться в «киров»: Киров и Кировская — разные
// города, склеивать их нельзя. Тип убираем, имя — нет.
//
// Модуль чистый — тесты tests/logist-mobile-city-norm.test.mjs.

import { shortCity } from "./format"

/**
 * Тип населённого пункта в начале или конце строки: «с.», «д.», «г.»,
 * «ст-ца», «пос.» и т.п. Только как отдельное слово — не часть имени.
 */
const SETTLEMENT_TYPE =
  /^(с|д|г|пос|п|х|ст|сл|м|рп|пгт|гп|дп|кп|снт|аул|улус|ж\/д ?р-?т|ст-?ца)\.?\s+/i
const SETTLEMENT_TYPE_TAIL = /\s+(с|д|г|пос|п|х|ст|сл|м|рп|пгт|гп|дп|аул|улус|ст-?ца)\.?$/i

/**
 * Города, которые ATI до сих пор пишет советскими названиями.
 *
 * Зачем: справочник биржи отдаёт «Свердловск г., Свердловская область» — город,
 * переименованный в 1991 году. Геокодер такого города не знает (или знает
 * одноимённый посёлок в Луганской области), справочник ATI тоже — и на этом
 * ломались сразу две вещи. Живой замер ПК-версии: маршрут «Ярославль →
 * Свердловск г.» остался одним плечом с 1062 км порожнего возврата, карта не
 * нарисовалась («точек маршрута пока нет»), а додобор написал «в радиусе 150 км
 * грузов не нашлось» — хотя из Екатеринбурга в пуле лежали грузы домой.
 *
 * Ключ — нормализованный вариант, значение — как город называется сейчас.
 */
const CITY_ALIASES: Record<string, string> = {
  свердловск: "екатеринбург",
  горький: "нижний новгород",
  куйбышев: "самара",
  ленинград: "санкт-петербург",
  молотов: "пермь",
  калинин: "тверь",
  сталинград: "волгоград",
  орджоникидзе: "владикавказ",
  устинов: "ижевск",
  андропов: "рыбинск",
  брежнев: "набережные челны",
  ворошиловград: "луганск",
  гурьев: "атырау",
  фрунзе: "бишкек",
}

/** Город так, как он называется сейчас: «Свердловск» → «Екатеринбург». */
export function canonicalCityName(value?: string | null): string {
  const key = stripCity(value)
  const alias = CITY_ALIASES[key]
  if (!alias) return ""
  return alias.replace(/(^|\s)([а-яё])/g, (_all, space: string, letter: string) => space + letter.toUpperCase())
}

/** Нормализованный ключ города: «ворсино» из «Ворсино с. (Боровский р-н)». */
function stripCity(value?: string | null): string {
  if (!value) return ""
  // Сначала короткая форма (без области, без улицы)
  let city = shortCity(value)
  if (!city || city === "—") return ""

  // Уточнения в скобках: «(Боровский р-н)», «(Волжский р-н)» и всё в них
  city = city.replace(/\([^)]*\)/g, " ").trim()

  // Префикс «г.»/«город» — на случай, если shortCity не снял
  city = city.replace(/^(г|город)\.?\s+/i, "")

  // Тип населённого пункта в начале и в конце — как отдельное слово
  city = city.replace(SETTLEMENT_TYPE, "")
  city = city.trim().replace(SETTLEMENT_TYPE_TAIL, "")

  // Приведение к единому виду
  return city
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[«»"'.,]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}

/**
 * Ключ города с учётом переименований: «Свердловск г.» и «Екатеринбург» — один
 * город. Без этого машина «стоит в Свердловске», а груз ждёт «из
 * Екатеринбурга», и обратка не подхватывается, хотя это одна и та же точка.
 */
export function normalizeCityKey(value?: string | null): string {
  const key = stripCity(value)
  if (!key) return ""
  return CITY_ALIASES[key] ?? key
}

/**
 * Городской округ из скобок: «г.о. Домодедово» из
 * «Константиново с. (г.о. Домодедово)».
 *
 * Зачем: ATI пишет муниципалитет в скобках, и сёло этого округа — по
 * факту тот же город для логиста. Машина, привезшая груз в Константиново,
 * уже дома, если база — Домодедово. Без этого помощник считает порожний
 * возврат 36 км и приезд домой на сутки позже, чем на самом деле.
 *
 * Берём ТОЛЬКО городской округ («г.о.»), не район («р-н»): Ворсино и
 * Денисово — оба Боровского района, но это разные сёла, ехать между ними
 * надо. «(регион)» не округ — иначе все города склеятся в одно место.
 */
export function cityDistrictKey(value?: string | null): string {
  if (!value) return ""
  const city = shortCity(value)
  if (!city || city === "—") return ""
  const match = city.match(/\(\s*г\.?\s*о\.?\s*([^)]+?)\s*\)/i)
  if (!match) return ""
  return match[1]
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[«»"'.,]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
}

/**
 * Одно ли это место для машины: тот же город ИЛИ тот же городской округ.
 *
 * «Домодедово» и «Константиново с. (г.о. Домодедово)» — одно место: база
 * рядом, возврат домой не нужен. «Москва» и «Москва (регион)» — тоже.
 */
export function samePlace(a?: string | null, b?: string | null): boolean {
  const ka = normalizeCityKey(a)
  const kb = normalizeCityKey(b)
  if (!ka || !kb) return false
  if (ka === kb) return true
  const da = cityDistrictKey(a)
  const db = cityDistrictKey(b)
  if (!da && !db) return false
  if (da && da === kb) return true
  if (db && db === ka) return true
  return da !== "" && da === db
}

/**
 * Одинаковые ли это города (с нормализацией). Пустые не равны ничему.
 */
export function sameCity(a?: string | null, b?: string | null): boolean {
  const ka = normalizeCityKey(a)
  const kb = normalizeCityKey(b)
  if (!ka || !kb) return false
  return ka === kb
}
