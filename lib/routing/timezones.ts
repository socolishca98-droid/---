/** Обратная карта: ключ региона → IANA-пояс. Собирается один раз. */
const BY_REGION = new Map<string, string>()
for (const [zone, regions] of Object.entries(ZONES)) {
  for (const region of regions) {
    if (!BY_REGION.has(region)) BY_REGION.set(region, zone)
  }
}

/**
 * Часовой пояс региона. null — регион не распознан; вызывающий код обязан
 * пометить расчёт как «пояс не определён», а не подставлять Москву.
 */
export function timeZoneForRegion(region: string | null | undefined): string | null {
  return BY_REGION.get(key(region)) ?? null
}

