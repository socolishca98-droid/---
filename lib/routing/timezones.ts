// Часовой пояс по региону — справочные данные, а не логика.
//
// Почему таблица, а не «Moscow по умолчанию»: рейс Екатеринбург → Красноярск
// идёт через два пояса, и «погрузка в 8 утра» — это время склада, а не сервера
// и не время логиста. Если подставить всем Москву, окна сдвинутся на 2–4 часа,
// и расчёт начнёт врать молча.
//
// Почему не по долготе: границы поясов в России не совпадают с меридианами
// (Якутия, Сахалин, Магадан), и «по координатам» ошибается на границах.
//
// Если регион не найден — возвращается null, а вызывающий код обязан сказать
// об этом в assumptions, а не притворяться, что пояс известен.

/** Ключ региона в том же виде, в котором сравнивает Distance Engine. */
function key(region: string | null | undefined): string {
  return String(region ?? "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/\s+(область|край|республика|обл\.?|респ\.?|автономный округ|ао)$/i, "")
    .replace(/[^a-zа-я0-9 -]/gi, "")
    .trim()
}

