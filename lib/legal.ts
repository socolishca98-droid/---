// lib/legal.ts
//
// Согласие на обработку персональных данных (152-ФЗ).
//
// Зачем отдельный модуль: согласие — это не галочка «на всякий случай», а
// юридический факт, который нужно уметь показать: кто согласился, когда и с
// какой редакцией документов. Поэтому версия документов живёт в одном месте,
// а при её смене прежние согласия остаются с прежней версией — видно, что
// человек принимал именно ту редакцию, которая действовала на тот момент.
//
// Важно про разделение обязанностей: компания, которая ведёт в Loginex своих
// сотрудников и водителей, является оператором их персональных данных.
// Loginex обрабатывает данные по её поручению (обработчик) и сам по себе не
// распоряжается этими данными. Поэтому в документах сказаны оба лица.

/** Текущая редакция документов. Меняйте при любой правке текста. */
export const CONSENT_VERSION = "2026-10-13"

/** Ссылки на документы — используются в интерфейсе и в письмах. */
export const LEGAL_LINKS = {
  privacy: "/privacy",
  terms: "/terms",
} as const

/** Человекочитаемое название оператора сервиса (владелец платформы). */
export function operatorName(): string {
  return String(process.env.LEGAL_OPERATOR_NAME ?? "").trim() || "Соколов Владислав Владимирович"
}

/** Контакт для обращений по персональным данным (почта оператора). */
export function operatorEmail(): string {
  return String(process.env.LEGAL_OPERATOR_EMAIL ?? "").trim() || "privacy@loginex.local"
}

/** Текст согласия, который показывается при регистрации. */
export const CONSENT_TEXT =
  "Я согласен на обработку моих персональных данных на условиях " +
  "политики конфиденциальности, и принимаю условия использования сервиса"

/** Что писать в интерфейсе, если документы ещё не заполнены реквизитами. */
export function legalNotice(): string {
  return (
    `Оператор персональных данных: ${operatorName()}. ` +
    `Вопросы по обработке данных — ${operatorEmail()}.`
  )
}
