/** Приводим название региона к нижнему регистру без лишних пробелов и точек. */
function normalizeRegion(name: string): string {
  return name
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/\s+/g, " ")
    .replace(/[.,]/g, "")
    .trim()
}

/** Федеральный округ по названию региона; null — регион не распознан. */
export function districtForRegion(regionName: string | null | undefined): FederalDistrict | null {
  if (!regionName) return null
  const name = normalizeRegion(regionName)
  if (!name) return null
  // Сначала точные корни подлиннее — «нижегородская» не должна ловиться как «новгородская»
  let best: { root: string; district: FederalDistrict } | null = null
  for (const [root, district] of REGION_ROOTS) {
    if (!name.includes(root)) continue
    if (!best || root.length > best.root.length) best = { root, district }
  }
  return best?.district ?? null
}

/**
 * Цена литра дизеля для расчёта рейса.
 *
 * Порядок: цена региона базы (там машина заправляется перед выездом) →
 * средняя по России. Никогда не ноль и не «примерно»: результат всегда
 * с датой среза, чтобы логист понимал, насколько цифра свежая.
 */
export function fuelPriceForRegion(regionName: string | null | undefined): number {
  const district = districtForRegion(regionName)
  return district ? FUEL_PRICE_BY_DISTRICT[district] : FUEL_PRICE_RUSSIA
}

/** Подпись для интерфейса: «81 ₽/л · ЦФО · Росстат, 5 октября 2026». */
export function fuelPriceNote(regionName: string | null | undefined): string {
  const district = districtForRegion(regionName)
  const price = district ? FUEL_PRICE_BY_DISTRICT[district] : FUEL_PRICE_RUSSIA
  const priceText = `${Math.round(price)} ₽/л`
  const where = district ? district : "средняя по России"
  return `${priceText} · ${where} · Росстат, ${FUEL_PRICE_DATE}`
}
