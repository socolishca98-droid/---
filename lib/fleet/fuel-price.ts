// Разброс между регионами — не мелочь: Дальний Восток дороже Центра на 16 ₽/л,
// и на 1000 км это больше 2500 ₽ на машине с расходом 30 л/100 км.
//
// Данные вписаны в код, а не тянутся из сети: у приложения нет источника цен,
// а тихая подстановка «примерных» цифр без даты — хуже, чем цифра с датой.
// Когда цены обновятся, меняется только таблица ниже.

