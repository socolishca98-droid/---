-- строки остаются валидными.
--
-- SQLite не умеет ADD COLUMN IF NOT EXISTS, поэтому идемпотентность
-- обеспечивает применяющий скрипт: он смотрит PRAGMA table_info и добавляет
-- колонку только когда её нет (как и в остальных миграциях проекта).
--
-- Откат: SQLite не умеет DROP COLUMN в старых версиях — откат делается
-- пересозданием таблицы из docs/eta-migration.md, либо колонка просто
-- остаётся пустой (на расчёт она не влияет).

