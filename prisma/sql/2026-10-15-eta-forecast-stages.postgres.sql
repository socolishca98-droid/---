-- 2026-10-15: связь прогноза с этапами рейса (PostgreSQL)
--
-- Зачем: прогноз хранился отдельно от шкалы этапов. При пересчёте было
-- непонятно, на каком состоянии рейса посчитано то или иное время, и
-- нельзя было сопоставить прогноз этапа с его фактом.
--
-- Колонка nullable и добавляется без значения по умолчанию: существующие
-- строки остаются валидными. Откат:
--   ALTER TABLE "EtaForecast" DROP COLUMN "stagesJson";
--
-- Идемпотентно: повторное применение ничего не ломает (ADD COLUMN IF NOT
-- EXISTS). Именно это проверяет scripts/verify-pg-migration.mjs.

ALTER TABLE "EtaForecast" ADD COLUMN IF NOT EXISTS "stagesJson" TEXT;
