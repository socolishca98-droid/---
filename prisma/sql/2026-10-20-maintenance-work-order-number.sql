-- 2026-10-20: номер заказ-наряда в журнале ремонтов — SQLite (разработка)
--
-- Зачем: логист записывает ремонт машины со СТО, и на бумаге у работы есть
-- номер заказ-наряда. Без поля его приходилось держать в описании, и потом
-- по бумаге было не найти запись.
--
-- Только добавление nullable-поля: существующие записи остаются валидными,
-- данные не теряются, откат — DROP COLUMN (SQLite 3.35+).
--
-- SQLite не умеет ADD COLUMN IF NOT EXISTS — идемпотентность обеспечивает
-- проверка наличия столбца в PRAGMA (см. шаблон 2026-10-19). При ручном
-- применении через psql/pgadmin прогонять один раз.

ALTER TABLE "MaintenanceLog" ADD COLUMN "workOrderNumber" TEXT;
